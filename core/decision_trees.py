QUALITY = {
    "BEST": ("Melhor resposta", 4),
    "SUBOPTIMAL": ("Correta, mas subótima", 3),
    "PLAUSIBLE": ("Plausível, mas incorreta", 1),
    "WRONG": ("Totalmente incorreta", 0),
}

FEEDBACK = {
    "BEST": "É a decisão mais segura, proporcional e alinhada ao raciocínio baseado em evidências para este momento.",
    "SUBOPTIMAL": "A conduta tem fundamento, mas deixa de considerar um elemento importante do contexto, da gravidade ou do stewardship.",
    "PLAUSIBLE": "A alternativa parece defensável à primeira vista, mas se apoia em uma associação ou prioridade clínica inadequada.",
    "WRONG": "A conduta não responde ao problema central e pode atrasar diagnóstico, tratamento ou encaminhamento adequado.",
}

