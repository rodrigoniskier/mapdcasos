def _profile_index(case):
    if case.category != ClinicalCase.Category.BACTERIA:
        raise ValueError("Árvore decisória disponível apenas para casos bacterianos nesta etapa.")
    order = int(case.order)
    if not 1 <= order <= 20:
        raise ValueError("Caso bacteriano fora da faixa B01–B20.")
    return ((order - 1) // 2) + 1


def _ordered_options(case_code, node):
    options = deepcopy(node["options"])
    return sorted(
        options,
        key=lambda opt: hashlib.sha256(
            f"{case_code}:{node['id']}:{opt['id']}".encode("utf-8")
        ).digest(),
    )


def get_tree(case):
    base = SCENARIOS[_profile_index(case)]
    variant = 1 if int(case.order) % 2 else 2
    nodes = []
    for node in base["nodes"]:
        rendered = deepcopy(node)
        rendered["options"] = _ordered_options(case.code, rendered)
        nodes.append(rendered)
    return {
        "case_code": case.code,
        "title": base["title"],
        "focus": base["focus"],
        "variant": variant,
        "variant_note": (
            "Primeiro episódio, sem tratamento específico prévio."
            if variant == 1
            else "Quadro persistente após medidas caseiras/sintomáticas, sem tratamento etiológico prévio."
        ),
        "sources": deepcopy(base["sources"]),
        "nodes": nodes,
        "max_points": sum(max(option["points"] for option in node["options"]) for node in nodes),
    }


def find_option(tree, node_id, option_id):
    node = next((item for item in tree["nodes"] if item["id"] == node_id), None)
    if not node:
        return None, None
    option = next((item for item in node["options"] if item["id"] == option_id), None)
    return node, option
